import React from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({next:0,kill:vi.fn(),dismiss:vi.fn()}));
vi.mock("react-native-gesture-handler", () => ({ GestureHandlerRootView: "GestureRoot", ScrollView: "ScrollView" }));
vi.mock('react-native',()=>({ Easing: { in: (fn: unknown) => fn, out: (fn: unknown) => fn, cubic: "cubic", quad: "quad" }, AccessibilityInfo: { isReduceMotionEnabled: async () => false, addEventListener: () => ({ remove() {} }) },View:'View',Text:'Text',TextInput:'Input',Pressable:'Pressable',ScrollView:'ScrollView',KeyboardAvoidingView:'KAV',Modal:'Modal',Platform:{OS:'android'},Keyboard:{dismiss:mocks.dismiss},useWindowDimensions:()=>({width:390,height:844}),Animated:{View:'AnimatedView',Value:class{interpolate(){return 0;}},timing:()=>({start:(done:any)=>done?.({finished:true}),stop(){}})},StyleSheet:{create:(s:unknown)=>s}}));
vi.mock('react-native-safe-area-context',()=>({useSafeAreaInsets:()=>({top:24,bottom:20,left:0,right:0})}));
vi.mock('lucide-react-native',()=>({ChevronLeft:'ChevronLeft',Check:'Check',Code2:'Code2',Folders:'Folders',History:'History',Pencil:'Pencil',Plus:'Plus',RefreshCw:'RefreshCw',Settings:'Settings',Settings2:'Settings2',TerminalSquare:'TerminalSquare',X:'X'}));
vi.mock('../../hooks/useTheme',()=>({useTheme:()=>({theme:'dark'})}));
vi.mock('../../hooks/useInlineEditCancel',()=>({useInlineEditCancel:vi.fn()}));
vi.mock('../../theme/colors',()=>({getThemeTokens:()=>({brand:'#63e6ae',bgCardSolid:'#22272e',textPrimary:'#fff'}),readableTextOn:()=> '#000'}));
vi.mock('../../i18n',()=>({getMessages:()=>({common:{close:'Cerrar'}})}));
vi.mock('expo-crypto',()=>({randomUUID:()=>String(++mocks.next)}));
vi.mock('../../components/NativeTerminalSession',()=>({default:'Session'}));
vi.mock('../../components/ServerSnippetsTab',()=>({default:'TerminalTools'}));
vi.mock('../../components/server-snippets/terminal-preferences',()=>({getTerminalPreferences:vi.fn(async()=>({fontSize:14,historyOrder:['codex','claude','commands'],historyVisible:['codex','claude','commands']}))}));
vi.mock('../../api/client/terminal',()=>({killTerminalSession:mocks.kill}));
vi.mock('../../lib/terminal-command-history',()=>({pushCommandHistory:vi.fn()}));
vi.mock('../../lib/session-state',()=>({loadSessionState:()=>({language:'es'})}));
import { NativeTerminalScreen } from './NativeTerminalScreen';
import { NativeModuleContext, dismissNativeModuleDialog } from '../main/native-module-context';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT=true;
let tree:ReactTestRenderer;
const back=vi.fn();
const render=(revision=1,selectedView?:string,visible=true)=><NativeModuleContext.Provider value={{key:'box:terminal',visible,insideWorkspace:true,viewRevision:revision,selectedView}}><NativeTerminalScreen panelId="remote-context" token="account" onBack={back}/></NativeModuleContext.Provider>;
const sessions=()=>tree.root.findAllByType('Session' as any);
const tools=()=>tree.root.findByType('TerminalTools' as any);
const press=async(label:string)=>act(async()=>tree.root.findAllByType('Pressable' as any).find(node=>node.props.accessibilityLabel===label)!.props.onPress());
beforeEach(()=>{mocks.next=0;mocks.kill.mockClear();back.mockClear();});
afterEach(async()=>{if(tree)await act(async()=>tree.unmount());});
it('uses the web dock order and independent panels; back closes the panel without closing its PTY',async()=>{
 await act(async()=>{tree=create(render());});
 const dock=tree.root.findByProps({testID:'terminal-floating-actions'});
 expect(dock.findAllByType('Pressable' as any).map(n=>n.props.accessibilityLabel)).toEqual(['Historial','Fragmentos','Consolas']);
 expect(sessions()[0].props.fontSize).toBe(14);
 const inject=vi.fn(),blur=vi.fn();
 await act(async()=>{sessions()[0].props.onRegisterInjector(inject);sessions()[0].props.onRegisterActions({blur,reconnect:vi.fn()});});
 await press('Historial');
 expect(blur).toHaveBeenCalledOnce();expect(mocks.dismiss).toHaveBeenCalled();
 expect(tools().props.tab).toBe('historial');expect(tools().props.hideTabs).toBe(true);
 expect(sessions()[0].props.active).toBe(false);
 const sameTools=tools();
 await act(async()=>{expect(dismissNativeModuleDialog('box:terminal')).toBe(true);});
 expect(sessions()[0].props.active).toBe(true);expect(back).not.toHaveBeenCalled();
 expect(dismissNativeModuleDialog('box:terminal')).toBe(false);
 await press('Fragmentos');expect(tools()).toBe(sameTools);expect(tools().props.tab).toBe('snippets');
 await act(async()=>tools().props.onSnippetAvailabilityChange(true));
 await press('Nuevo snippet');expect(tools().props.newSnippetRequest).toBe(1);
 await act(async()=>{tools().props.injectIntoTerminal('command');tools().props.onAfterRun();});
 expect(inject).toHaveBeenCalledWith('command');expect(sessions()).toHaveLength(1);
 await press('Configuración');expect(tools().props.tab).toBe('config');
 await act(async()=>tools().props.onPreferencesChange({fontSize:18}));expect(sessions()[0].props.fontSize).toBe(18);
 expect(mocks.kill).not.toHaveBeenCalled();
});
it('keeps consoles alive when hiding, renaming and switching; closes only the chosen PTY and keeps the list open',async()=>{
 await act(async()=>{tree=create(render(1,'new'));});
 await act(async()=>tree.update(render(2,'new')));
 expect(sessions().map(n=>n.props.sessionId)).toEqual(['1','2']);expect(sessions().map(n=>n.props.active)).toEqual([false,true]);
 await act(async()=>tree.update(render(3,undefined,false)));expect(sessions().every(n=>!n.props.active)).toBe(true);
 await act(async()=>tree.update(render(3)));
 await press('Consolas');await press('Renombrar Terminal 1');
 await act(async()=>tree.root.findByType('Input' as any).props.onChangeText('Logs'));
 await press('Guardar Terminal 1');
 expect(JSON.stringify(tree.toJSON())).toContain('Logs');
 await press('Cerrar Terminal 2');
 expect(mocks.kill).toHaveBeenCalledWith('remote-context','account','2');expect(sessions().map(n=>n.props.sessionId)).toEqual(['1']);
 expect(tree.root.findAllByProps({testID:'terminal-floating-actions'})).toHaveLength(0);
 await press('Nueva terminal');expect(sessions().map(n=>n.props.sessionId)).toEqual(['1','3']);
 await press('Volver al chat');expect(back).toHaveBeenCalledOnce();expect(mocks.kill).toHaveBeenCalledTimes(1);
});
it('positions the dock above the keyboard/accessory bar, lays it out horizontally in short viewports and reconnects the selected console',async()=>{
 await act(async()=>{tree=create(render());});
 await act(async()=>sessions()[0].props.onViewportChange({bottom:357,height:150}));
 expect(tree.root.findByProps({testID:'terminal-floating-actions'}).props.style).toContainEqual(expect.objectContaining({bottom:377,flexDirection:'row'}));
 const reconnect=vi.fn();
 await act(async()=>{sessions()[0].props.onRegisterActions({reconnect,blur:vi.fn()});sessions()[0].props.onStatusChange('error');});
 await press('Consolas');await press('Reconectar terminal');expect(reconnect).toHaveBeenCalledOnce();
 expect(sessions()).toHaveLength(1);expect(mocks.kill).not.toHaveBeenCalled();
});
