set -euo pipefail
IFS=$'\n\t'

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

source "${ROOT_DIR}/scripts/install-common.sh"

require_root
require_command git

GIT_PULL=true
GIT_BRANCH="${GIT_BRANCH:-$DEFAULT_GIT_BRANCH}"
SKIP_BACKEND=false
SKIP_FRONTEND=false
APP_DOMAIN="${APP_DOMAIN:-}"

extract_host_from_url() {
  local url="$1"
  printf '%s\n' "${url}" | sed -E 's#^[a-zA-Z]+://([^/:]+).*$#\1#'
}

refresh_nginx_upstreams() {
  local backend_port="$1"
  local frontend_port="$2"
  local nginx_file="${PANEL_NGINX_SITE_AVAILABLE}"

  if [[ ! -f "${nginx_file}" ]]; then
    # Same template install.sh writes — SSOT in scripts/install-common.sh.
    write_panel_nginx_vhost "${backend_port}" "${frontend_port}" "${APP_DOMAIN}" "${ROOT_DIR}"
    return
  fi

  # The i18n block injected below is generated by the SAME function the full
  # template uses (install-common.sh), passed in on argv so this patcher can no
  # longer drift from the vhost install.sh writes.
  python3 - "${nginx_file}" "${backend_port}" "${frontend_port}" "$(panel_nginx_i18n_block "${ROOT_DIR}")" "$(panel_nginx_extracted_block "${ROOT_DIR}")" <<'PY'
from pathlib import Path
import re
import sys

nginx_file = Path(sys.argv[1])
backend_port = sys.argv[2]
frontend_port = sys.argv[3]
i18n_block = sys.argv[4]
extracted_block = sys.argv[5]
content = nginx_file.read_text(encoding="utf-8")

content = re.sub(
    r"(upstream\s+panel_api\s*\{\s*server\s+127\.0\.0\.1:)\d+(;)",
    rf"\g<1>{backend_port}\2",
    content,
    count=1,
    flags=re.S,
)
content = re.sub(
    r"(upstream\s+panel_frontend\s*\{\s*server\s+127\.0\.0\.1:)\d+(;)",
    rf"\g<1>{frontend_port}\2",
    content,
    count=1,
    flags=re.S,
)

# Idempotently inject the disk-served i18n blocks into pre-existing configs
# (this function only patches upstream ports on upgrades, so installs created
# before the i18n offload wouldn't otherwise get it). Inserted right before
# the catch-all `location / {`; the @node_frontend fallback is a named
# location so its position within server{} doesn't matter.
if "location /i18n/" not in content:
    # Command substitution strips trailing newlines; restore the blank line the
    # block needs before the `location / {` it is spliced in front of.
    block = i18n_block.rstrip("\n") + "\n\n"
    content, n = re.subn(r"(?m)^  location / \{", block + "  location / {", content, count=1)
    if n == 0:
        sys.stderr.write("warning: could not locate 'location / {' to insert i18n blocks\n")

if "location ^~ /scripts/extracted/" not in content:
    block = extracted_block.rstrip("\n") + "\n\n"
    content, n = re.subn(r"(?m)^  location / \{", block + "  location / {", content, count=1)
    if n == 0:
        sys.stderr.write("warning: could not locate 'location / {' to insert extracted scripts block\n")

nginx_file.write_text(content, encoding="utf-8")
PY

  ln -sfn "${nginx_file}" "${PANEL_NGINX_SITE_ENABLED}"
  rm -f /etc/nginx/sites-enabled/default
  nginx -t
  systemctl reload nginx
}

parse_args() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --skip-git-pull)
        GIT_PULL=false
        shift
        ;;
      --branch)
        GIT_BRANCH="$2"
        shift 2
        ;;
      --skip-backend)
        SKIP_BACKEND=true
        shift
        ;;
      --skip-frontend)
        SKIP_FRONTEND=true
        shift
        ;;
      --domain)
        APP_DOMAIN="$2"
        shift 2
        ;;
      --help|-h)
        cat <<'EOF'
Usage: sudo bash update.sh [options]

Options:
  --skip-git-pull   Rebuild from the current checkout without pulling
  --branch <name>   Branch to pull when git update is enabled
  --skip-backend    Do not update backend
  --skip-frontend   Do not update frontend
  --domain <host>   Override nginx server_name when reloading panel config
EOF
        exit 0
        ;;
      *)
        fail "Unknown option: $1"
        ;;
    esac
  done
}

main() {
  parse_args "$@"

  if [[ "${GIT_PULL}" == "true" ]]; then
    info "Updating git checkout from branch ${GIT_BRANCH}"
    git_update_branch "${ROOT_DIR}" "${GIT_BRANCH}"
  fi

  if [[ "${SKIP_BACKEND}" != "true" ]]; then
    bash "${ROOT_DIR}/backend/update.sh" --skip-git-pull
  fi

  if [[ "${SKIP_FRONTEND}" != "true" ]]; then
    bash "${ROOT_DIR}/frontend/update.sh" --skip-git-pull
  fi

  local backend_port
  local frontend_port
  local frontend_site_url

  backend_port="$(get_env_value "${ROOT_DIR}/backend/.env" PORT || printf '%s' "${DEFAULT_BACKEND_PORT}")"
  frontend_port="$(get_env_value "${ROOT_DIR}/frontend/.env" PORT || get_env_value "${ROOT_DIR}/frontend/.env" PORT_FRONTEND || printf '%s' "${DEFAULT_FRONTEND_PORT}")"
  frontend_site_url="$(get_env_value "${ROOT_DIR}/frontend/.env" SITE_URL || true)"

  if [[ -z "${APP_DOMAIN}" && -n "${frontend_site_url}" ]]; then
    APP_DOMAIN="$(extract_host_from_url "${frontend_site_url}")"
  fi

  if command -v nginx >/dev/null 2>&1; then
    info "Refreshing nginx upstream ports"
    refresh_nginx_upstreams "${backend_port}" "${frontend_port}"
  fi

  # Disk hygiene (idempotent; also retrofits installs older than these guards):
  # no cwd core dumps, pm2 log rotation, and sweep of stale build artifacts
  # (core.* inside the repo, unreferenced pnpm store packages).
  setup_coredump_guard
  ensure_pm2_logrotate
  cleanup_build_artifacts "${ROOT_DIR}"

  info "Update completed"
  info "Backend: 127.0.0.1:${backend_port}"
  info "Frontend: 127.0.0.1:${frontend_port}"
}

main "$@"
