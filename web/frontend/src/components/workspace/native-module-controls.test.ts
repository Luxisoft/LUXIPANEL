import { afterEach, expect, it, vi } from "vitest";
import { createControllerScope } from "./controller-scope";
import { mountNativeModuleControls } from "./native-module-controls";
afterEach(() => { document.body.replaceChildren(); vi.unstubAllGlobals(); });
it("preserves live filter listeners, restores parked controls and cleans up their ownership", async () => {
  vi.stubGlobal("EventSource", class { close() {} });
  document.body.innerHTML = '<div class="lxp-workspace-quick-drawer"><div data-module-header-native-slot></div><div id="module" data-internal-module="expo"><div id="pane"><input id="expo-env-filter-text" value="kept"></div></div></div>';
  const root = document.querySelector<HTMLElement>("#module")!, slot = document.querySelector("[data-module-header-native-slot]")!;
  const scope = createControllerScope(root, new URL("https://panel.example/panel/expo"));
  const input = scope.document.getElementById("expo-env-filter-text")!;
  const listener = vi.fn(); input.addEventListener("input", listener);
  const stop = mountNativeModuleControls(scope);
  expect(slot.contains(input)).toBe(true);
  expect(scope.document.getElementById("expo-env-filter-text")).toBe(input);
  input.dispatchEvent(new Event("input", {bubbles:true})); expect(listener).toHaveBeenCalledOnce();
  root.hidden = true; await new Promise(resolve => setTimeout(resolve, 0));
  expect(root.contains(input)).toBe(true); expect(slot.contains(input)).toBe(false);
  root.hidden = false; await new Promise(resolve => setTimeout(resolve, 0));
  expect(slot.contains(input)).toBe(true);
  expect((input as HTMLInputElement).value).toBe("kept");
  stop(); expect(root.contains(input)).toBe(true); expect(slot.children).toHaveLength(0);
  expect(root.querySelector("[data-module-native-source-row]")).toBeNull();
  scope.dispose();
});
