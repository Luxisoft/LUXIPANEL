it("keeps shared overflow lookup isolated to the visible module", async () => {
  vi.stubGlobal("EventSource", class { close() {} });
  document.body.innerHTML = '<div class="lxp-workspace-quick-drawer"><header><div data-module-header-search-slot></div><div data-module-header-native-slot></div><div data-topbar-content></div></header><div id="a" data-internal-module="expo"><section><input id="expo-env-filter-text"></section></div><div id="b" data-internal-module="cron" hidden><section><input id="cron-text-filter"></section></div></div>';
  const a = createControllerScope(document.getElementById("a")!, new URL("https://panel.example/panel/expo"));
  const b = createControllerScope(document.getElementById("b")!, new URL("https://panel.example/panel/cron"));
  const ai = a.document.getElementById("expo-env-filter-text")!, bi = b.document.getElementById("cron-text-filter")!;
  const stopA = mountNativeModuleControls(a), stopB = mountNativeModuleControls(b);
  const popup = document.querySelector("[data-topbar-content]")!;
  popup.append(ai);
  expect(a.document.getElementById("expo-env-filter-text")).toBe(ai);
  expect(b.document.getElementById("expo-env-filter-text")).toBeNull();
  a.root.hidden = true; b.root.hidden = false;
  await new Promise(resolve => setTimeout(resolve, 0));
  popup.append(bi);
  expect(a.document.getElementById("cron-text-filter")).toBeNull();
  expect(b.document.getElementById("cron-text-filter")).toBe(bi);
  stopA(); stopB(); a.dispose(); b.dispose();
});
