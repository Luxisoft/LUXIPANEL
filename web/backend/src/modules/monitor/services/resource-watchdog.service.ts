/**
 * Resource watchdog service — installs/operates the auto-reboot watchdog on
 * the CONNECTED server.
 *
 * The watchdog is a root systemd service (`luxipanel-resource-watchdog`)
 * running a small POSIX-sh sampling loop generated from the panel config:
 * when CPU and/or RAM usage stays at/above the configured maximum for the
 * sustained window, it logs the reason, records state for the panel and runs
 * `systemctl reboot`. It runs on-box, so it works 24/7 with no panel session.
 *
 * Safety rails baked into the script:
 *  - sustained window (min 2 consecutive samples — a single spike never reboots)
 *  - boot grace: never reboots within N minutes after boot (no reboot loops)
 *  - cooldown: minimum time between watchdog reboots, persisted across boots
 *
 * Install/update uses the shared MutationStep executor (`applyStepsLive`):
 * root file writes go SFTP-tmp + `sudo cp` and systemctl runs via sudo argv,
 * matching the write-behind worker semantics. All operations land on the
 * client server through the per-request Executor — nothing runs on the panel
 * host.
 */

import type { Executor } from "../../../shared/executor/index.js";
import { quoteArg, quoteCmd } from "../../../shared/executor/index.js";
import { createModuleLogger } from "../../../shared/logger/index.js";
import {
  applyStepsLive,
  type MutationStep,
} from "../../../shared/remote-cache/submit-mutation.js";
import type { WatchdogConfig, WatchdogStatus } from "../models/watchdog.model.js";

const log = createModuleLogger("resource-watchdog");

export const WATCHDOG_UNIT = "luxipanel-resource-watchdog";
const SCRIPT_DIR = "/usr/local/lib/luxipanel";
const SCRIPT_PATH = `${SCRIPT_DIR}/resource-watchdog.sh`;
const UNIT_PATH = `/etc/systemd/system/${WATCHDOG_UNIT}.service`;
const STATE_DIR = "/var/lib/luxipanel/resource-watchdog";
const STATE_FILE = `${STATE_DIR}/state.json`;
const LOG_FILE = "/var/log/luxipanel-resource-watchdog.log";

/** Consecutive breaching samples required. Never below 2 (spike protection). */
export function sustainedSamples(config: WatchdogConfig): number {
  return Math.max(2, Math.round(config.sustainedSeconds / config.intervalSeconds));
}

/**
 * Render the on-box watchdog loop. All interpolated values are
 * schema-validated integers (or the empty string for a disabled threshold),
 * so the script body is injection-free by construction.
 */
export function renderWatchdogScript(config: WatchdogConfig): string {
  const cpuMax = config.cpuPercent == null ? "" : String(config.cpuPercent);
  const memMax = config.memPercent == null ? "" : String(config.memPercent);
  const sustain = sustainedSamples(config);
  const bootGraceSec = config.bootGraceMinutes * 60;
  const cooldownSec = config.cooldownMinutes * 60;

  return `#!/bin/sh
# LUXIPANEL resource watchdog — AUTO-GENERATED by the panel; do not edit.
# Reboots this server after sustained CPU/RAM pressure. Managed from
# /panel/monitor (module "monitor").

CPU_MAX=${cpuMax}
MEM_MAX=${memMax}
INTERVAL=${config.intervalSeconds}
SUSTAIN=${sustain}
BOOT_GRACE=${bootGraceSec}
COOLDOWN=${cooldownSec}

STATE_DIR=${STATE_DIR}
STATE_FILE=${STATE_FILE}
LOG=${LOG_FILE}

mkdir -p "$STATE_DIR"
touch "$LOG" 2>/dev/null
chmod 644 "$LOG" 2>/dev/null

log_line() {
  echo "$(date '+%Y-%m-%d %H:%M:%S') $1" >> "$LOG"
}

# Prints "<busy+idle total> <idle>" jiffies (idle = idle + iowait).
read_cpu() {
  awk '/^cpu /{print $2+$3+$4+$5+$6+$7+$8+$9 " " $5+$6}' /proc/stat
}

read_mem_pct() {
  awk '/MemTotal/{t=$2} /MemAvailable/{a=$2} END{ if (t > 0) printf "%d", (100 * (t - a)) / t; else print 0 }' /proc/meminfo
}

log_line "watchdog started (cpu_max=$CPU_MAX mem_max=$MEM_MAX interval=$INTERVAL sustain=$SUSTAIN)"

cpu_count=0
mem_count=0
set -- $(read_cpu)
prev_total=$1
prev_idle=$2

while :; do
  sleep "$INTERVAL"

  set -- $(read_cpu)
  total=$1
  idle=$2
  dt=$((total - prev_total))
  di=$((idle - prev_idle))
  prev_total=$total
  prev_idle=$idle
  cpu=0
  [ "$dt" -gt 0 ] && cpu=$(( (100 * (dt - di)) / dt ))

  mem=$(read_mem_pct)

  reason=""
  if [ -n "$CPU_MAX" ]; then
    if [ "$cpu" -ge "$CPU_MAX" ]; then cpu_count=$((cpu_count + 1)); else cpu_count=0; fi
    [ "$cpu_count" -ge "$SUSTAIN" ] && reason="cpu $cpu% >= $CPU_MAX%"
  fi
  if [ -z "$reason" ] && [ -n "$MEM_MAX" ]; then
    if [ "$mem" -ge "$MEM_MAX" ]; then mem_count=$((mem_count + 1)); else mem_count=0; fi
    [ "$mem_count" -ge "$SUSTAIN" ] && reason="ram $mem% >= $MEM_MAX%"
  fi

  [ -z "$reason" ] && continue

  now=$(date +%s)
  up=$(awk '{printf "%d", $1}' /proc/uptime)
  if [ "$up" -lt "$BOOT_GRACE" ]; then
    log_line "skip reboot ($reason): dentro del boot grace (uptime $up s < $BOOT_GRACE s)"
    cpu_count=0; mem_count=0
    continue
  fi

  last=0
  [ -f "$STATE_DIR/last-reboot" ] && last=$(cat "$STATE_DIR/last-reboot" 2>/dev/null)
  case "$last" in ''|*[!0-9]*) last=0 ;; esac
  if [ $((now - last)) -lt "$COOLDOWN" ]; then
    log_line "skip reboot ($reason): cooldown activo"
    cpu_count=0; mem_count=0
    continue
  fi

  echo "$now" > "$STATE_DIR/last-reboot"
  printf '{"lastTriggeredAt":%s,"reason":"%s","cpu":%s,"mem":%s}' "$now" "$reason" "$cpu" "$mem" > "$STATE_FILE"
  chmod 644 "$STATE_FILE" 2>/dev/null
  log_line "REBOOT: $reason (sostenido $SUSTAIN muestras x $INTERVAL s)"
  wall "LUXIPANEL watchdog: reiniciando el servidor ($reason)" 2>/dev/null || true
  sync
  systemctl reboot
  exit 0
done
`;
}

export function renderWatchdogUnit(): string {
  return `[Unit]
Description=LUXIPANEL resource watchdog (auto-reboot on sustained CPU/RAM pressure)
Documentation=man:systemd.service(5)
After=multi-user.target

[Service]
Type=simple
ExecStart=${SCRIPT_PATH}
Restart=always
RestartSec=10
Nice=-10

[Install]
WantedBy=multi-user.target
`;
}

export const resourceWatchdogService = {
  /**
   * Install or update the watchdog on the client server and (re)start it
   * with the given thresholds. Idempotent: rewrites script + unit, reloads
   * systemd, enables at boot and restarts the loop.
   */
  async install(executor: Executor, config: WatchdogConfig): Promise<void> {
    const steps: MutationStep[] = [
      { type: "sh", argv: ["mkdir", "-p", SCRIPT_DIR, STATE_DIR], sudo: true },
      { type: "writeFile", path: SCRIPT_PATH, content: renderWatchdogScript(config), mode: "0755", root: true },
      { type: "writeFile", path: UNIT_PATH, content: renderWatchdogUnit(), mode: "0644", root: true },
      { type: "sh", argv: ["systemctl", "daemon-reload"], sudo: true },
      { type: "sh", argv: ["systemctl", "enable", WATCHDOG_UNIT], sudo: true },
      { type: "sh", argv: ["systemctl", "restart", WATCHDOG_UNIT], sudo: true },
    ];
    await applyStepsLive(executor, steps);
    log.info(
      {
        target: executor.target.id,
        cpuPercent: config.cpuPercent,
        memPercent: config.memPercent,
        sustainedSeconds: config.sustainedSeconds,
      },
      "Resource watchdog installed/updated on client server",
    );
  },

  /** Stop the watchdog and disable it at boot. No-op when never installed. */
  async disable(executor: Executor): Promise<void> {
    const exists = await executor.exec(quoteCmd("test", ["-f", UNIT_PATH]), { timeoutMs: 10_000 });
    if (exists.exitCode !== 0) return;
    await applyStepsLive(executor, [
      { type: "sh", argv: ["systemctl", "disable", "--now", WATCHDOG_UNIT], sudo: true },
    ]);
    log.info({ target: executor.target.id }, "Resource watchdog disabled on client server");
  },

  /** Live unit + last-trigger state, read without sudo in one round-trip. */
  async status(executor: Executor): Promise<WatchdogStatus> {
    const body = [
      `if [ -f ${quoteArg(UNIT_PATH)} ]; then printf 'installed=yes\\n'; else printf 'installed=no\\n'; fi`,
      `printf 'active=%s\\n' "$(systemctl is-active ${WATCHDOG_UNIT} 2>/dev/null)"`,
      `printf 'enabled=%s\\n' "$(systemctl is-enabled ${WATCHDOG_UNIT} 2>/dev/null)"`,
      `printf 'state=%s\\n' "$(cat ${quoteArg(STATE_FILE)} 2>/dev/null | tr -d '\\n')"`,
    ].join("; ");
    const r = await executor.exec(`sh -c ${quoteArg(body)}`, { timeoutMs: 15_000 });

    const line = (key: string): string =>
      r.stdout
        .split("\n")
        .find((l) => l.startsWith(`${key}=`))
        ?.slice(key.length + 1)
        .trim() ?? "";

    let lastTriggeredAt: number | null = null;
    let lastReason: string | null = null;
    const stateRaw = line("state");
    if (stateRaw) {
      try {
        const state = JSON.parse(stateRaw) as { lastTriggeredAt?: unknown; reason?: unknown };
        if (typeof state.lastTriggeredAt === "number" && Number.isFinite(state.lastTriggeredAt)) {
          lastTriggeredAt = state.lastTriggeredAt;
        }
        if (typeof state.reason === "string" && state.reason) lastReason = state.reason;
      } catch {
        // Corrupt/legacy state file — surface "never triggered" instead of failing.
      }
    }

    return {
      installed: line("installed") === "yes",
      active: line("active") === "active",
      enabledOnBoot: line("enabled") === "enabled",
      lastTriggeredAt,
      lastReason,
    };
  },
};
