import { useEffect, useMemo, useRef, useState } from "react";
import styles from "../DataTableSettings.module.css";
import { ENV } from "../../config/env";
import { type Messages } from "../../i18n";
import {
  getApiToken,
  rotateApiToken,
  type ApiTokenInfo,
} from "../../api/client";
import { DocLink, InlineAlert, docUrl } from "./shared";

export function ApiTab({ token, t }: { token: string; t: Messages }) {
  const [tokenInfo, setTokenInfo] = useState<ApiTokenInfo | null>(null);
  const [email, setEmail] = useState<string | null>(null);
  const [plaintext, setPlaintext] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [success, setSuccess] = useState("");
  const [copied, setCopied] = useState<string | null>(null);
  const loaded = useRef(false);

  const endpointUrl = useMemo(() => {
    const base = (ENV.apiUrl || "").replace(/\/+$/, "");
    return `${base}/v1/api/auth/token`;
  }, []);

  function formatDate(iso: string | null): string {
    if (!iso) return "—";
    try {
      return new Date(iso).toLocaleString();
    } catch {
      return iso;
    }
  }

  function maskedDisplay(prefix: string, last4: string): string {
    return `${prefix}…${last4}`;
  }

  async function refresh(): Promise<void> {
    setError("");
    try {
      const data = await getApiToken(token);
      setEmail(data.email);
      setTokenInfo(data.token);
      if (data.plaintext) {
        setPlaintext(data.plaintext);
        setSuccess(t.dataTableSettings.apiTab.autoGenerated);
      }
    } catch (err) {
      setError(err instanceof Error ? err.message : t.common.error);
    }
  }

  useEffect(() => {
    if (loaded.current) return;
    loaded.current = true;
    void refresh();
  }, [token]);

  async function copyToClipboard(value: string, key: string) {
    if (!value || value === "—") return;
    try {
      await navigator.clipboard.writeText(value);
      setCopied(key);
      setTimeout(() => setCopied(null), 1500);
    } catch {
      setCopied(`${key}:err`);
      setTimeout(() => setCopied(null), 1500);
    }
  }

  async function handleRotate() {
    if (!confirm(t.dataTableSettings.apiTab.rotateConfirm)) return;
    setBusy(true);
    setError("");
    setSuccess("");
    try {
      const result = await rotateApiToken(token);
      if (typeof result.token === "string") setPlaintext(result.token);
      await refresh();
      setSuccess(t.dataTableSettings.apiTab.rotated);
    } catch (err) {
      setError(err instanceof Error ? err.message : t.common.error);
    } finally {
      setBusy(false);
    }
  }

  const subtitle = tokenInfo
    ? t.dataTableSettings.apiTab.tokenActive
    : t.dataTableSettings.apiTab.loadingState;

  const lastUsed = tokenInfo?.lastUsedAt
    ? `${t.dataTableSettings.apiTab.lastUsedPrefix} ${formatDate(tokenInfo.lastUsedAt)}`
    : t.dataTableSettings.apiTab.notUsedYet;
  const existingHint = tokenInfo
    ? `${t.dataTableSettings.apiTab.createdAt} ${formatDate(tokenInfo.createdAt)} · ${lastUsed}`
    : "—";

  function copyLabel(key: string, original: string): string {
    if (copied === key) return t.dataTableSettings.apiTab.copied;
    if (copied === `${key}:err`) return t.dataTableSettings.apiTab.copyError;
    return original;
  }

  return (
    <div className="space-y-3">
      <h4 className={`lp-modal-label ${styles.tabHeading}`}>
        {t.dataTableSettings.apiTab.heading}
      </h4>
      <p className="text-xs opacity-70">
        {t.dataTableSettings.apiTab.helpBefore} <code>POST /v1/api/auth/token</code>{t.dataTableSettings.apiTab.helpAfter}{" "}
        <DocLink href={docUrl("/documentation/api")} label={t.dataTableSettings.apiTab.docsLink} />
      </p>

      <InlineAlert message={error} />
      <InlineAlert message={success} tone="ok" />

      <div
        className={`${styles.apiInfoCard} rounded-lg p-3`}
      >
        <div className="mb-2">
          <p className={`${styles.apiInfoCardHeading} text-sm font-semibold`}>{t.dataTableSettings.apiTab.tokenLabel}</p>
          <p className="text-xs opacity-70">{subtitle}</p>
        </div>

        {plaintext ? (
          <div
            className={`${styles.plaintextBox} mb-3 rounded-md p-2`}
          >
            <p className="mb-1 text-xs">
              <strong>{t.dataTableSettings.apiTab.onlyShownNow}</strong> {t.dataTableSettings.apiTab.saveSafely}
            </p>
            <div className="flex items-center gap-2">
              <code
                className={`${styles.codeSnippet} flex-1 break-all rounded-md p-1 text-xs`}
              >
                {plaintext}
              </code>
              <button
                type="button"
                className="lp-modal-btn lp-modal-btn--ghost"
                onClick={() => void copyToClipboard(plaintext, "plaintext")}
              >
                {copyLabel("plaintext", t.dataTableSettings.apiTab.copy)}
              </button>
            </div>
          </div>
        ) : null}

        {tokenInfo ? (
          <div className="space-y-3">
            <div>
              <span className="lp-modal-label">{t.dataTableSettings.apiTab.currentToken}</span>
              <div className="flex items-center gap-2">
                <code
                  className={`${styles.codeSnippet} flex-1 rounded-md p-1 text-xs`}
                >
                  {maskedDisplay(tokenInfo.prefix, tokenInfo.last4)}
                </code>
                <button
                  type="button"
                  className="lp-modal-btn lp-modal-btn--ghost"
                  onClick={() => void copyToClipboard(maskedDisplay(tokenInfo.prefix, tokenInfo.last4), "masked")}
                >
                  {copyLabel("masked", t.dataTableSettings.apiTab.copyPrefix)}
                </button>
              </div>
              <p className="text-xs opacity-70">{existingHint}</p>
            </div>

            <div>
              <span className="lp-modal-label">{t.dataTableSettings.apiTab.registeredEmail}</span>
              <div className="flex items-center gap-2">
                <code
                  className={`${styles.codeSnippet} flex-1 rounded-md p-1 text-xs`}
                >
                  {email ?? "—"}
                </code>
                <button
                  type="button"
                  className="lp-modal-btn lp-modal-btn--ghost"
                  onClick={() => void copyToClipboard(email ?? "", "email")}
                >
                  {copyLabel("email", t.dataTableSettings.apiTab.copy)}
                </button>
              </div>
              <p className="text-xs opacity-70">{t.dataTableSettings.apiTab.registeredEmailHelp}</p>
            </div>

            <div>
              <span className="lp-modal-label">{t.dataTableSettings.apiTab.endpoint}</span>
              <div className="flex items-center gap-2">
                <code
                  className={`${styles.codeSnippet} flex-1 break-all rounded-md p-1 text-xs`}
                >
                  {endpointUrl}
                </code>
                <button
                  type="button"
                  className="lp-modal-btn lp-modal-btn--ghost"
                  onClick={() => void copyToClipboard(endpointUrl, "endpoint")}
                >
                  {copyLabel("endpoint", t.dataTableSettings.apiTab.copy)}
                </button>
              </div>
              <p className="text-xs opacity-70">
                {t.dataTableSettings.apiTab.endpointHelpBefore} <code>email</code> {t.dataTableSettings.apiTab.endpointHelpMid} <code>apiToken</code> {t.dataTableSettings.apiTab.endpointHelpAfter}
              </p>
            </div>
          </div>
        ) : null}

        <div className="mt-3 flex gap-2">
          <button
            type="button"
            className="lp-modal-btn lp-modal-btn--ghost"
            onClick={handleRotate}
            disabled={busy || !tokenInfo}
          >
            {t.dataTableSettings.apiTab.rotate}
          </button>
        </div>
      </div>
    </div>
  );
}
